import {loadSupplierCatalog,appendSupplierCatalog} from '../lib/supplier-catalog.mjs';
import {loadDoorCatalog,appendDoorCatalog} from '../lib/door-catalog.mjs';
import {loadFrontCatalog,appendFrontCatalog} from '../lib/cabinet-fronts.mjs';
import {applyFurnitureSets} from '../lib/furniture-sets.mjs';
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {applyProductModels} from '../lib/product-models.mjs';
import {normalizeCatalog} from '../lib/catalog.mjs';
import {selectDriveMappings} from '../lib/drive-map.mjs';
import {packWebAssets} from '../lib/assets.mjs';
import {loadMediaApprovals} from '../lib/media-approvals.mjs';
import {applyCatalogPrices,verifyPriceEvidence} from '../lib/catalog-pricing.mjs';
import {loadNativeDictionaries,verifyNativeCatalogue} from '../lib/native-locales.mjs';
import {applyStoreDiscounts,verifyStoreHistoryEvidence} from '../lib/store-discounts.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const sourceBytes=await readFile(path.join(root,'data/catalog-source.json'));
const source=JSON.parse(sourceBytes);
const identities=JSON.parse(await readFile(path.join(root,'data/catalog-identities.json'),'utf8'));
if(createHash('sha256').update(sourceBytes).digest('hex')!==identities.sourceCatalogSha256)throw new Error('Catalogue identity source has changed; review the PDF mapping before publication.');
const {catalog,media,report}=normalizeCatalog(source,{identities});
const pricing=JSON.parse(await readFile(path.join(root,'data/catalog-prices.json'),'utf8'));
applyCatalogPrices(catalog,source,pricing);
await verifyPriceEvidence(root,pricing);
const history=JSON.parse(await readFile(path.join(root,'data/price-history.json'),'utf8'));
const discountPolicy=JSON.parse(await readFile(path.join(root,'data/discount-policy.json'),'utf8'));
await verifyStoreHistoryEvidence(root,history);
applyStoreDiscounts(catalog,history,discountPolicy);
const models=JSON.parse(await readFile(path.join(root,'data/product-models.json'),'utf8'));
applyProductModels(catalog,source,models,{sourceCatalogSha256:createHash('sha256').update(sourceBytes).digest('hex'),identitiesSha256:createHash('sha256').update(await readFile(path.join(root,'data/catalog-identities.json'))).digest('hex')});
const setBytes=await readFile(path.join(root,'data/furniture-sets.json'));
const setMapping=JSON.parse(setBytes);
applyFurnitureSets(catalog,setMapping,{sourceCatalogSha256:createHash('sha256').update(sourceBytes).digest('hex'),identitiesSha256:createHash('sha256').update(await readFile(path.join(root,'data/catalog-identities.json'))).digest('hex'),pdfSha256:createHash('sha256').update(await readFile(path.join(root,setMapping.sourcePdf))).digest('hex')});
catalog.meta.furnitureSetsVersion=createHash('sha256').update(setBytes).digest('hex');
const brand=JSON.parse(await readFile(path.join(root,'data/brand.json'),'utf8'));
catalog.brand={...catalog.brand,name:brand.name,slogan:brand.slogan,domain:brand.domain};
if(!catalog.products.length) throw new Error('No verified products to publish');
if(Object.values(report.translationPending).some(Boolean)) throw new Error('Product technical translations must be completed before publication: '+JSON.stringify(report.translationPending));
const approvedMedia=await loadMediaApprovals({root,media});
const native=await loadNativeDictionaries(root,{testOnly:approvedMedia.testOnly});
catalog.meta.mediaVersion=approvedMedia.mediaVersion;
const ownerMedia={};let suppliers=null;
if(!approvedMedia.testOnly){
 const doors=await loadDoorCatalog(root),fronts=await loadFrontCatalog(root);
 appendDoorCatalog(catalog,doors.data,doors.version);appendFrontCatalog(catalog,fronts.data,fronts.version);
 suppliers=await loadSupplierCatalog(root);appendSupplierCatalog(catalog,suppliers.data,suppliers.version);
 for(const data of [doors.data,fronts.data])for(const p of data.products)for(const [index,hash]of p.assetHashes.entries())ownerMedia[p.id+':'+index]=data.assets[hash].path;
 verifyNativeCatalogue(catalog,native.dictionaries);
}
const mediaProof=Object.fromEntries(Object.entries(approvedMedia.manifest.references).map(([reference,urlHash])=>[reference,approvedMedia.manifest.images[urlHash].outputSha]));
const supplierAssetHashes=suppliers?Object.fromEntries(Object.values(suppliers.data.products).flatMap(p=>p.images.map(url=>[url,url.split('/').at(-1).split('.')[0]]))):{};
const assets=await packWebAssets(path.join(root,'web'),{externalAssets:supplierAssetHashes});if(suppliers)Object.assign(assets,suppliers.detailAssets);
if(!assets['/']) throw new Error('Missing storefront');
let drive={};
try {
 const m=JSON.parse(await readFile(path.join(root,'artifacts/drive-manifest.json'),'utf8'));
 drive=selectDriveMappings(m,media);
} catch(e) {if(e.code!=='ENOENT') throw e;}
const localeRuntime=(await readFile(path.join(root,'web/locale-runtime.js'),'utf8')).replace(/^export /gm,'');
const nativeInit=Object.entries(native.dictionaries).map(([lang,payload])=>'registerLocaleDictionary('+JSON.stringify(lang)+','+JSON.stringify(payload)+');').join('\n');
const seo=(await readFile(path.join(root,'web/seo-core.js'),'utf8')).replace(/^import .*locale-runtime.*\r?\n/gm,'').replace(/^export /gm,'');
const server=localeRuntime+'\n'+nativeInit+'\n'+seo+'\n'+(await readFile(path.join(root,'lib/server.mjs'),'utf8')).replace(/^import .*from '\.\/seo\.mjs';\r?\n/m,'').replace(/^export /gm,'');
catalog.meta.releaseHash=createHash('sha256').update(server).update(JSON.stringify({catalog,assets,media,drive,brand})).digest('hex');
const bundle=server+'\nconst catalog='+JSON.stringify(catalog)+';\nconst assets='+JSON.stringify(assets)+';\nconst media='+JSON.stringify(media)+';\nconst drive='+JSON.stringify(drive)+';\nconst brand='+JSON.stringify(brand)+';\nconst ownerMedia='+JSON.stringify(ownerMedia)+';\nconst mediaProof='+JSON.stringify(mediaProof)+';\nexport default createApplication(catalog,assets,media,drive,fetch,brand,mediaProof,ownerMedia);\n';
await mkdir(path.join(root,'dist/server'),{recursive:true});
await mkdir(path.join(root,'dist/.openai'),{recursive:true});
await writeFile(path.join(root,'dist/server/index.js'),bundle,'utf8');
await copyFile(path.join(root,'.openai/hosting.json'),path.join(root,'dist/.openai/hosting.json'));
await mkdir(path.join(root,'artifacts'),{recursive:true});
await writeFile(path.join(root,'artifacts/catalog-validation.json'),JSON.stringify(report,null,2),'utf8');
console.log(JSON.stringify({built:true,products:catalog.products.length,categories:catalog.categories.length,bundleBytes:Buffer.byteLength(bundle),releaseHash:catalog.meta.releaseHash,...report}));
